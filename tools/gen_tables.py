"""Generate src/diacritized.inc and src/default_pos.inc from Python bifonia.

Two tables live in the Python source, not in a data file: the diacritic table
`_DIACRITIZED` of bifonia/__init__.py and `DEFAULT_POS` of bifonia/data.py.
They are copied here in Python's dict order, which the port depends on: the
reverse maps keep the last value for a repeated key.

Usage:
  python -I tools/gen_tables.py diacritized > src/diacritized.inc
  python -I tools/gen_tables.py default_pos > src/default_pos.inc
"""
import importlib.metadata
import json
import sys

import bifonia
from bifonia import data


def q(text):
    return json.dumps(text, ensure_ascii=False)


def main():
    print("// Generated by tools/gen_tables.py; do not edit.")
    print(f"// bifonia {importlib.metadata.version('bifonia')}.\n")
    if sys.argv[1] == "default_pos":
        print("struct DefaultPosEntry { const char* word; const char* pos; };")
        print(f"static const DefaultPosEntry kDefaultPos[{len(data.DEFAULT_POS)}] = {{")
        for word, pos in data.DEFAULT_POS.items():
            print(f"  {{{q(word)}, {q(pos)}}},")
        print("};")
        return
    print("struct DiacritizedEntry { const char* base; const char* sense; const char* form; };")
    print(f"static const DiacritizedEntry kDiacritized[{len(bifonia._DIACRITIZED)}] = {{")
    for (base, sense), form in bifonia._DIACRITIZED.items():
        print(f"  {{{q(base)}, {q(sense)}, {q(form)}}},")
    print("};")


if __name__ == "__main__":
    main()
