"""Generate src/unicode_tables.inc from the running Python's Unicode database.

The C++ port must match Python's str.lower, str.upper, str.isspace,
str.isalnum (the `\\w` class of `re`), str.isupper, str.isdigit, float()'s
decimal-digit transform and unicodedata.normalize("NFD") with the category
Mn filter. The tables are taken from Python itself rather than from ICU, so the
two agree on the same Unicode version; the version is written into the
generated file.

Usage: python -I tools/gen_unicode_tables.py > src/unicode_tables.inc
"""
import sys
import unicodedata

MAX = 0x110000
SIGMA = "Σ"


def surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def ranges(predicate):
    out, start = [], None
    for cp in range(MAX + 1):
        hit = cp < MAX and not surrogate(cp) and predicate(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


# Case-ignorable and cased are derived from the final-sigma behaviour itself,
# since unicodedata exposes neither property:
#   "A" + c + "Σ" -> ς  iff  ignorable(c) or cased(c)
#   "AΣ" + c      -> ς  iff  ignorable(c) or not cased(c)
#   c + "Σ"       -> ς  iff  cased(c) and not ignorable(c)
def ignorable(c):
    return ("A" + c + SIGMA).lower()[-1] == "ς" and ("A" + SIGMA + c).lower()[1] == "ς"


def cased(c):
    # Only consulted for non-ignorable code points, which is all Python asks.
    return (c + SIGMA).lower()[-1] == "ς"


def hangul(cp):
    return 0xAC00 <= cp <= 0xD7A3


def write_mapping(w, name, mapping, width):
    w(f"static const CaseEntry {name}[{len(mapping)}] = {{\n")
    for cp, to in mapping:
        assert len(to) <= width
        padded = [ord(c) for c in to] + [0] * (width - len(to))
        w(f"  {{0x{cp:X}, {{{', '.join(f'0x{x:X}' for x in padded)}}}, {len(to)}}},\n")
    w("};\n\n")


def main():
    w = sys.stdout.write
    w("// Generated by tools/gen_unicode_tables.py; do not edit.\n")
    w(f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n\n")
    w("struct CaseEntry { char32_t cp; char32_t to[3]; unsigned char len; };\n")
    points = [cp for cp in range(MAX) if not surrogate(cp)]
    write_mapping(w, "kLower", [(cp, chr(cp).lower()) for cp in points
                                if cp != 0x03A3 and chr(cp).lower() != chr(cp)], 3)
    write_mapping(w, "kUpper", [(cp, chr(cp).upper()) for cp in points
                                if chr(cp).upper() != chr(cp)], 3)

    for name, pred in (("kSpace", str.isspace),
                       ("kWord", lambda c: c.isalnum() or c == "_"),
                       ("kIsUpper", str.isupper),
                       ("kIsDigit", str.isdigit),
                       ("kMn", lambda c: unicodedata.category(c) == "Mn"),
                       ("kCaseIgnorable", ignorable),
                       ("kCased", cased),
                       ("kPrintable", str.isprintable)):
        rs = ranges(pred)
        w(f"static const char32_t {name}[{len(rs)}][2] = {{\n")
        for lo, hi in rs:
            w(f"  {{0x{lo:X}, 0x{hi:X}}},\n")
        w("};\n\n")

    decimals = [(cp, unicodedata.decimal(chr(cp))) for cp in points
                if cp >= 0x80 and unicodedata.decimal(chr(cp), -1) >= 0]
    w(f"static const char32_t kDecimal[{len(decimals)}][2] = {{\n")
    for cp, value in decimals:
        w(f"  {{0x{cp:X}, {value}}},\n")
    w("};\n\n")

    # Full canonical decompositions (Hangul syllables are computed in code),
    # stored in one pool, and the non-zero canonical combining classes.
    decomp = []
    for cp in points:
        if hangul(cp):
            continue
        d = unicodedata.normalize("NFD", chr(cp))
        if d != chr(cp):
            decomp.append((cp, d))
    pool, entries = [], []
    for cp, d in decomp:
        entries.append((cp, len(pool), len(d)))
        pool.extend(ord(c) for c in d)
    w(f"static const char32_t kDecompPool[{len(pool)}] = {{\n")
    for i in range(0, len(pool), 8):
        w("  " + ", ".join(f"0x{x:X}" for x in pool[i:i + 8]) + ",\n")
    w("};\n\n")
    w("struct DecompEntry { char32_t cp; unsigned short offset; unsigned char len; };\n")
    w(f"static const DecompEntry kDecomp[{len(entries)}] = {{\n")
    for cp, off, n in entries:
        w(f"  {{0x{cp:X}, {off}, {n}}},\n")
    w("};\n\n")
    ccc = [(cp, unicodedata.combining(chr(cp))) for cp in points if unicodedata.combining(chr(cp))]
    w("struct CccEntry { char32_t cp; unsigned char ccc; };\n")
    w(f"static const CccEntry kCcc[{len(ccc)}] = {{\n")
    for cp, c in ccc:
        w(f"  {{0x{cp:X}, {c}}},\n")
    w("};\n")


if __name__ == "__main__":
    main()
